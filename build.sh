#!/bin/sh
# Builds dist/background_dry_run.js = Config + Collector + runner (self-contained)
set -e
cd "$(dirname "$0")"
mkdir -p dist
{
  echo "/* Driftwood POC – background dry run (generated by build.sh; do not edit) */"
  cat src/script_includes/ConfigNowConfig.js
  echo
  cat src/script_includes/ConfigNowCollector.js
  echo
  cat src/background/run_dry.js
} > dist/background_dry_run.js
echo "built dist/background_dry_run.js"
{
  echo "/* Driftwood snapshot exporter (generated by build.sh; do not edit) */"
  cat src/script_includes/ConfigNowConfig.js
  echo
  cat src/script_includes/ConfigNowCollector.js
  echo
  cat src/background/run_export.js
} > dist/export_snapshot.js
echo "built dist/export_snapshot.js"
